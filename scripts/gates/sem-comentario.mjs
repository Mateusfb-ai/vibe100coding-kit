#!/usr/bin/env node
// Código de produto não carrega comentário, emoji nem procedência de ferramenta.
// O porquê vai para docs/DECISOES.md ou learnings/. Diretiva de compilador fica.
// Pastas: kit.json → "pastasLimpas" (padrão: src). Se a pasta não existe, ok.
import { readFileSync } from "node:fs";
import path from "node:path";
import { RAIZ, config, listar, reprovar } from "./_arquivos.mjs";

const pastas = [...(config().pastasLimpas || ["src"]), "scripts/gates/_fixtures"];
const DIRETIVA = /^\s*\/\/\s*(@ts-|eslint-|swiftlint:|prettier-|biome-|#region|#endregion|swift-tools-version)/;
const EMOJI = /[\u{1F300}-\u{1FAFF}\u{2600}-\u{27BF}]/u;
const problemas = [];
for (const arq of listar(pastas, [".ts", ".tsx", ".js", ".jsx", ".mjs", ".swift", ".py", ".go", ".rs"])) {
  const linhas = readFileSync(arq, "utf8").split("\n");
  linhas.forEach((l, i) => {
    const rel = `${path.relative(RAIZ, arq)}:${i + 1}`;
    const semString = l.replace(/(["'`])(?:\\.|(?!\1).)*\1/g, '""');
    if (/^\s*(\/\/|#(?!!)|\/\*|\*\/|\* )/.test(semString) && !DIRETIVA.test(l)) problemas.push(`${rel} comentário`);
    if (EMOJI.test(l)) problemas.push(`${rel} emoji`);
    if (/generated by|co-authored-by|claude|copilot|chatgpt/i.test(semString)) problemas.push(`${rel} procedência de ferramenta`);
  });
}
reprovar("sem-comentario", problemas);
